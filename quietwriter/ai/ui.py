    def _wait_for_workers(self, timeout_ms=3000) -> bool:
        running = [worker for worker in self._workers if worker.isRunning()]
        if not running:
            return True
        deadline = time.monotonic() + max(0, timeout_ms) / 1000.0
        for worker in running:
            remaining_ms = max(0, int((deadline - time.monotonic()) * 1000))
            if remaining_ms <= 0 or not worker.wait(remaining_ms):
                return False
        return not any(worker.isRunning() for worker in self._workers)

    def shutdown(self, timeout_ms=4000) -> bool:
        # A book switch may leave a cancelled network worker finishing in the
        # background. Stop every retained worker before Qt destroys the panel.
        for worker in list(self._workers):
            if worker.isRunning():
                worker.stop()
        return self._wait_for_workers(timeout_ms)

