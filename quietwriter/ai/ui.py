class ProviderChatWorker(QThread):
    token = Signal(str)
    thinking = Signal(str)
    finished_ok = Signal()
    failed = Signal(str)
    cancelled = Signal()

    def __init__(self, provider, model: str, messages: list[dict], options=None):
        super().__init__()
        self.provider = provider
        self.model = model
        self.messages = messages
        self.options = options or {}
        self._stop = False

    def stop(self):
        self._stop = True
        try:
            self.provider.cancel_active()
        except Exception:
            pass

    def run(self):
        try:
            for chunk in self.provider.stream_chat(self.model, self.messages, **self.options):
                if self._stop:
                    self.cancelled.emit(); return
                if chunk.thinking: self.thinking.emit(chunk.thinking)
                if chunk.content: self.token.emit(chunk.content)
            if self._stop:
                self.cancelled.emit()
            else:
                self.finished_ok.emit()
        except Exception as exc:
            if self._stop:
                self.cancelled.emit()
            else:
                self.failed.emit(str(exc))



def markdown_to_html(text: str) -> str:
    """Return only the HTML body fragment generated by Qt Markdown.

    QTextDocument.toHtml() returns a complete HTML document with its own body
    defaults. Embedding that inside another QTextBrowser document produced
    invalid nested HTML and could preserve light/dark colours from a previous
    theme. A clean fragment inherits the card colours we set explicitly.
    """
    doc = QTextDocument()
    doc.setMarkdown(text or '')
    rendered = doc.toHtml()
    match = re.search(r'<body[^>]*>(.*)</body>', rendered, flags=re.IGNORECASE | re.DOTALL)
    return match.group(1) if match else rendered


