    def is_busy(self) -> bool:
        return bool(self.worker and self.worker.isRunning())

    def _icon_path(self, name: str):
        from pathlib import Path
        return str(Path(__file__).resolve().parents[1] / 'icons' / f'{name}.svg')

    def _set_action_state(self, busy: bool):
        self.action_button.setIcon(QIcon(self._icon_path('stop' if busy else 'send')))
        self.action_button.setToolTip(tr('ai.stop_ai', 'Stop AI') if busy else tr('ai.send', 'Versturen'))
        self.action_button.setAccessibleName(tr('ai.stop_ai', 'Stop AI') if busy else tr('ai.send', 'Versturen'))

    def _action_clicked(self):
        if self.is_busy():
            self.stop_ai()
        else:
            self.send()

    def _has_manuscript_selection(self) -> bool:
        editor_page = getattr(self.main, 'editor_page', None)
        editor = getattr(editor_page, 'editor', None) if editor_page is not None else None
        return bool(editor and editor.textCursor().hasSelection())

    def refresh_quick_actions(self):
        busy = self.is_busy()
        has_selection = self._has_manuscript_selection()
        for action in QUICK_ACTIONS:
            button = self.quick_action_buttons.get(action.key)
            if not button:
                continue
            enabled = not busy and (has_selection or not action.requires_selection)
            button.setEnabled(enabled)
            if action.requires_selection and not has_selection:
                button.setToolTip(tr('ai.select_text_first', 'Selecteer eerst tekst in het manuscript.'))
            else:
                button.setToolTip(tr(f'ai.quick.{action.key}.tooltip', action.tooltip))

    def _apply_quick_action(self, key: str):
        action = QUICK_ACTION_BY_KEY.get(key)
        if not action or self.is_busy():
            return
        if action.requires_selection and not self._has_manuscript_selection():
            self.refresh_quick_actions()
            return
        self.input.setPlainText(tr(f'ai.quick.{action.key}.prompt', action.prompt))
        cursor = self.input.textCursor(); cursor.movePosition(QTextCursor.End); self.input.setTextCursor(cursor)
        self.input.setFocus()

    def _update_busy_buttons(self):
        busy=self.is_busy()
        self.action_button.setEnabled(True)
        self._set_action_state(busy)
        self.input.setEnabled(not busy)
        self.clear_button.setEnabled(not busy)
        has_book = self.store is not None
        self.planning_context_button.setEnabled(not busy and has_book)
        preview = self._chapter_planning_preview() if has_book else None
        self.chapter_planning_check.setEnabled(bool(preview and preview.text and not preview.error and not busy))
        self.refresh_quick_actions()

    def set_book(self, book):
        new_book_id = getattr(book, 'id', None) if book is not None else None
        if book is not None and new_book_id == self._book_id:
            # Conflict resolution/version restore may replace the live Book
            # object while keeping the same logical book. Keep an in-flight AI
            # request and its unsaved user message alive; only repoint storage
            # at the newly adopted live path.
            self.store = ConversationStore(book)
            return

        # Invalidate every callback that belongs to the previously visible book
        # before retiring an old worker. QThread signals are queued to the GUI
        # thread, so they may arrive only after this method has already swapped
        # self.store/self.messages to another book.
        self._book_generation += 1
        self._book_id = new_book_id
        self._planning_selection = PlanningSelection()
        self._pending_memory_suggestions = []
        self.memory_card.hide()
        self._active_request_id = None
        old_worker = self.worker
        if old_worker is not None and old_worker.isRunning():
            old_worker.stop()
        # Do not block the GUI waiting for a provider/network call to honour
        # cancellation. The old worker remains strongly referenced in
        # self._workers until its finished signal arrives, but it is no longer
        # the active worker for the newly selected book.
        self.worker = None

        self.render_timer.stop()
        self._finish_thinking()
        self.current_assistant = ''
        self._final_started = False
        self._active_context = None
        self._active_user_index = None
        self.store = ConversationStore(book) if book else None
        self.messages = self.store.load() if self.store else []
        self._warming_up = False
        self._warmup_attempted = bool(self.messages)
        self.context.setCurrentIndex(max(0, self.context.findData('chapter')))
        self.context_panel.hide(); self.context_toggle.setChecked(False)
        self._refresh_idle_context_summary()
        self._render_chat()
        self._update_busy_buttons()

    def _choose_planning_context(self):
        book = self.main.active_book()
        if not book or self.is_busy():
            return
        dialog = PlanningContextDialog(self, self.main.library, book, self._planning_selection)
        if dialog.exec() == QDialog.Accepted:
            self._planning_selection = dialog.selection()
            self._refresh_idle_context_summary()

