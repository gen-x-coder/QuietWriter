    def ensure_warmup(self):
        """Prepare a genuinely new Reader conversation without blocking the UI.

        No manuscript text is sent for this introduction. OpenRouter never
        receives a warm-up request: its welcome is local, so no book/persona
        data leaves the computer merely because the panel opens. Ollama may warm
        the selected local model in a worker thread. The first real question
        remains the first point at which manuscript text is sent.
        """
        if self.is_busy() or self.messages or self._warmup_attempted or self.store is None:
            return
        provider_name = str(self.main.settings.value('ai_provider', 'ollama') or 'ollama').lower()
        self._warmup_attempted = True
        if provider_name == 'openrouter':
            self.messages.append(ConversationStore.entry('assistant', tr(
                'ai.warmup.welcome',
                'Ik ben jouw meelees-assistent. Ik kan feedback geven op je eigen tekst, bijvoorbeeld met een persona-check, feitencheck en controles op continuïteit en consistentie. Selecteer gerust een tekstfragment en stel daar een vraag over; ik lees mee en adviseer, maar neem het schrijven niet van je over.'
            )))
            self.store.save(self.messages)
            self._render_chat()
            return
        provider, model = self._provider_model()
        if not model:
            self._warmup_attempted = False
            return
        context = ContextBundle(tr('ai.warmup.context_label', 'nog geen manuscriptcontext'), '', [])
        self._continue_send(
            provider, model, tr(
                'ai.warmup.prompt',
                'Start dit nieuwe gesprek met een korte introductie als mijn meelees-assistent. Leg uit dat je feedback, persona-checks, feitenchecks en controles op continuïteit en consistentie kunt doen, en dat ik tekst kan selecteren om daar een vraag over te stellen. Maak duidelijk dat jij meeleest en adviseert en het schrijven niet van mij overneemt. Schrijf of herschrijf geen manuscripttekst.'
            ), context, warmup=True
        )

    def _provider_model(self):
        provider = ProviderFactory.from_settings(self.main.settings)
        pname = str(self.main.settings.value('ai_provider', 'ollama') or 'ollama').lower()
        key = 'openrouter_model' if pname == 'openrouter' else 'ollama_model'
        return provider, str(self.main.settings.value(key, '') or '')

    def send(self):
        prompt = self.input.toPlainText().strip()
        if not prompt or self.is_busy(): return
        provider, model = self._provider_model()
        if not model:
            QMessageBox.information(self, 'AI', tr('ai.model_required', 'Kies eerst een AI-model in Instellingen.')); return
        builder = ContextBuilder(self.main)
        manuscript_context = builder.build(str(self.context.currentData() or 'chapter'))
        planning = self._planning_context_result()
        if planning.error:
            manuscript_context.pieces.append(tr('ai.context.planning_unavailable_piece', 'Planning niet beschikbaar — {error}', error=planning.error))
        elif planning.labels:
            manuscript_context.pieces.append(tr('ai.context.planning_piece', 'Planning: {labels}', labels=', '.join(planning.labels)))
        chapter_planning_text = self._active_chapter_planning_text()
        if chapter_planning_text:
            manuscript_context.pieces.append(tr('ai.context.chapter_sent_piece', 'Planning van huidig hoofdstuk: meegestuurd'))
        self.input.clear()
        self._continue_send(provider, model, prompt, manuscript_context, planning.text, chapter_planning_text)


    def _continue_send(self, provider, model: str, prompt: str, context, planning_text: str = '', chapter_planning_text: str = '', *, warmup: bool = False):
        self._active_context = context
        self._refresh_idle_context_summary()
        active_book = self.main.active_book()
        persona, persona_ok = read_optional_source(self.main.library.read_persona)
        if active_book:
            book_profile, profile_ok = read_optional_source(lambda: self.main.library.read_book_profile(active_book))
            book_memory, memory_ok = read_optional_source(lambda: self.main.library.read_book_memory(active_book))
        else:
            book_profile, profile_ok = '', True
            book_memory, memory_ok = '', True

        source_states = [
            (tr('context.persona', 'Schrijverspersona'), persona_ok),
            (tr('context.book_profile', 'Boekprofiel'), profile_ok),
            (tr('context.book_memory', 'Boekgeheugen'), memory_ok),
        ]
        for label, ok in source_states:
            if ok:
                continue
            try:
                context.pieces.remove(label)
            except ValueError:
                pass
            context.pieces.append(tr(
                'ai.context.source_corrupt_piece',
                '{source} beschadigd — niet meegestuurd',
                source=label,
            ))
        context_text=context.text

        system_prompt = build_system_prompt(
            persona=persona,
            book_profile=book_profile,
            book_memory=book_memory,
            planning_text=planning_text,
            chapter_planning_text=chapter_planning_text,
            context_label=context.label,
            context_text=context_text,
        )

        if warmup:
            self._active_user_index = None
        else:
            self.messages.append(ConversationStore.entry('user', prompt, {'pieces': context.pieces, 'scope': str(self.context.currentData() or 'chapter')}))
            self._active_user_index=len(self.messages)-1
        self._warming_up = bool(warmup)
        self.current_assistant=''; self._final_started=False; self._thinking_text=''
        thinking_requested = bool(self.main.settings.value('ai_disable_thinking', False, bool))
        provider_name = str(getattr(provider, 'name', '') or '')
        capability = str(self.main.settings.value(
            f'ai_thinking_can_disable/{provider_name}/{model}', 'unknown'
        ) or 'unknown').lower()
        # A checked but disabled UI control must never force an unsupported
        # provider parameter. Unknown/capability-only models may still receive
        # the best-effort request exactly as before.
        thinking_disabled = thinking_requested and capability != 'false'
        self._render_chat(streaming_placeholder=True)
        if not warmup:
            self._start_thinking(tr('ai.working', 'De Meelezer werkt') if thinking_disabled else tr('ai.thinking_base', 'Meelezen'))

        # QuietWriter sends the stable Reader context plus a limited recent chat.
        # A warm-up deliberately excludes manuscript text and uses a hidden user
        # instruction only to initialize the model and introduce its Reader role.
        recent=[{'role':m['role'],'content':m['content']} for m in self.messages[-6:] if m.get('role') in {'user','assistant'}]
        messages=[{'role':'system','content':system_prompt}] + recent
        if warmup:
            messages.append({'role':'user','content':prompt})
        self._request_serial += 1
        request_id = (self._book_generation, self._request_serial)
        provider_options = {}
        if thinking_disabled:
            if getattr(provider, 'name', '') == 'ollama':
                provider_options['think'] = False
            elif getattr(provider, 'name', '') == 'openrouter':
                provider_options['reasoning'] = {'enabled': False}
        worker = ProviderChatWorker(provider,model,messages,options=provider_options)
        self.worker = worker
        self._workers.add(worker)
        self._active_request_id = request_id
        worker.token.connect(lambda text, w=worker, rid=request_id: self._token(w, rid, text))
        worker.thinking.connect(lambda text, w=worker, rid=request_id: self._thinking(w, rid, text))
        worker.failed.connect(lambda err, w=worker, rid=request_id: self._fail(w, rid, err))
        worker.finished_ok.connect(lambda w=worker, rid=request_id: self._done(w, rid))
        worker.cancelled.connect(lambda w=worker, rid=request_id: self._chat_cancelled(w, rid))
        worker.finished.connect(lambda w=worker, rid=request_id: self._chat_thread_finished(w, rid))
        worker.start(); self._update_busy_buttons()

    def stop_ai(self):
        if self.worker and self.worker.isRunning():
            self.worker.stop()
            self.action_button.setEnabled(False)
            self._thinking_base = tr('ai.stop', 'Stoppen')
            self.thinking_button.setText(tr('ai.stopping', 'Stoppen…'))

    def _wait_for_workers(self, timeout_ms=3000) -> bool:
        running = [worker for worker in self._workers if worker.isRunning()]
        if not running:
            return True
        deadline = time.monotonic() + max(0, timeout_ms) / 1000.0
        for worker in running:
            remaining_ms = max(0, int((deadline - time.monotonic()) * 1000))
            if remaining_ms <= 0 or not worker.wait(remaining_ms):
                return False
        return not any(worker.isRunning() for worker in self._workers)

    def shutdown(self, timeout_ms=4000) -> bool:
        # A book switch may leave a cancelled network worker finishing in the
        # background. Stop every retained worker before Qt destroys the panel.
        for worker in list(self._workers):
            if worker.isRunning():
                worker.stop()
        return self._wait_for_workers(timeout_ms)

