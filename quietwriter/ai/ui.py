    def _request_is_current(self, worker, request_id) -> bool:
        return bool(
            worker is self.worker
            and request_id == self._active_request_id
            and request_id[0] == self._book_generation
        )

    def _thinking(self, worker, request_id, text):
        if not self._request_is_current(worker, request_id):
            return
        self._thinking_text += text
        self.thinking_details.setPlainText(self._thinking_text)
        cur = self.thinking_details.textCursor(); cur.movePosition(QTextCursor.End); self.thinking_details.setTextCursor(cur)

    def _finish_thinking(self):
        self.thinking_timer.stop(); self.thinking_details.clear(); self.thinking_details.hide(); self.thinking_button.hide(); self._thinking_text = ''

    def _token(self, worker, request_id, text):
        if not self._request_is_current(worker, request_id):
            return
        if not self._final_started:
            self._final_started = True; self._finish_thinking()
        self.current_assistant += text
        if not self.render_timer.isActive(): self.render_timer.start()

    def _done(self, worker, request_id):
        if not self._request_is_current(worker, request_id):
            return
        self._finish_thinking()
        if self.current_assistant.strip():
            context = self._active_context
            visible, suggestions = extract_memory_suggestions(self.current_assistant)
            if visible:
                self.messages.append(ConversationStore.entry('assistant', visible, {'pieces': context.pieces if context else []}))
            if self.store: self.store.save(self.messages)
            if suggestions:
                self._pending_memory_suggestions.extend(suggestions)
                self._show_memory_suggestion()
        self._active_user_index=None
        self.render_timer.stop(); self.current_assistant = ''; self._render_chat()

    def _fail(self, worker, request_id, err):
        if not self._request_is_current(worker, request_id):
            return
        self._finish_thinking(); self.current_assistant=''
        self.messages.append(ConversationStore.entry('assistant', f'Fout: {err}'))
        self._active_user_index=None
        if self.store: self.store.save(self.messages)
        self._render_chat()

    def _chat_cancelled(self, worker, request_id):
        if not self._request_is_current(worker, request_id):
            return
        self._finish_thinking(); self.render_timer.stop(); self.current_assistant=''
        # Een gestopte opdracht wordt niet als half gesprek bewaard.
        if self._active_user_index is not None and self._active_user_index == len(self.messages)-1:
            if self.messages[self._active_user_index].get('role') == 'user':
                self.messages.pop()
        self._active_user_index=None
        self._refresh_idle_context_summary()
        self._render_chat()

    def _chat_thread_finished(self, worker, request_id):
        # Een oude worker mag nooit een inmiddels nieuwere worker-reference
        # wissen. Dit kan gebeuren wanneer zijn queued finished-signaal pas na
        # een boekwissel (of een nieuwe aanvraag) door de GUI-thread wordt verwerkt.
        if self.worker is worker:
            self.worker = None
            if self._active_request_id == request_id:
                self._active_request_id = None
        self._workers.discard(worker)
        worker.deleteLater()
        self._update_busy_buttons()

    def apply_theme(self, theme_name: str):
        """Re-render rich chat content for the active QuietWriter theme."""
        self.theme_name = theme_name if theme_name in THEMES else 'Helder'
        theme = THEMES[self.theme_name]
        # QTextBrowser can otherwise retain its HTML document base brush across
        # a global QSS switch. Set the palette as well as rebuilding the HTML.
        palette = self.chat.palette()
        palette.setColor(QPalette.Base, QColor(theme['panel']))
        palette.setColor(QPalette.Text, QColor(theme['text']))
        self.chat.setPalette(palette)
        self._render_chat(streaming_placeholder=bool(self.current_assistant))

